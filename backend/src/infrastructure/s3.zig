const std = @import("std");
const Sha256 = std.crypto.hash.sha2.Sha256;
const Hmac = std.crypto.auth.hmac.sha2.HmacSha256;

/// Настройки S3; строки из load ссылаются на переданную карту окружения.
pub const Settings = struct {
    endpoint: []const u8,
    region: []const u8,
    bucket: []const u8,
    access_key: []const u8,
    secret_key: []const u8,

    /// Читает S3-переменные окружения и проверяет endpoint, бакет, регион и ключ доступа.
    /// S3_ACCESS_KEY_ID и S3_SECRET_ACCESS_KEY обязательны.
    pub fn load(env: *const std.process.Environ.Map) !Settings {
        const settings: Settings = .{
            .endpoint = std.mem.trimEnd(u8, env.get("S3_ENDPOINT") orelse "http://127.0.0.1:9000", "/"),
            .region = env.get("S3_REGION") orelse "us-east-1",
            .bucket = env.get("S3_BUCKET") orelse "media",
            .access_key = try required(env, "S3_ACCESS_KEY_ID"),
            .secret_key = try required(env, "S3_SECRET_ACCESS_KEY"),
        };

        try validateEndpoint(settings.endpoint);

        if (settings.bucket.len < 3 or settings.bucket.len > 63 or
            !std.ascii.isAlphanumeric(settings.bucket[0]) or
            !std.ascii.isAlphanumeric(settings.bucket[settings.bucket.len - 1]))
            return error.InvalidConfiguration;
        for (settings.bucket) |c| {
            if (!(std.ascii.isLower(c) or std.ascii.isDigit(c) or c == '-'))
                return error.InvalidConfiguration;
        }

        for (settings.region) |c| {
            if (!(std.ascii.isLower(c) or std.ascii.isDigit(c) or c == '-'))
                return error.InvalidConfiguration;
        }
        if (settings.region.len == 0) return error.InvalidConfiguration;

        for (settings.access_key) |c| {
            if (!(std.ascii.isAlphanumeric(c) or c == '-' or c == '_')) return error.InvalidConfiguration;
        }

        return settings;
    }
};

/// Владеет HTTP-клиентом с пулом соединений для подписанных S3-запросов.
/// После первого запроса структура должна оставаться по стабильному адресу.
pub const S3 = struct {
    client: std.http.Client,
    io: std.Io,
    allocator: std.mem.Allocator,
    endpoint: []const u8,
    region: []const u8,
    bucket: []const u8,
    access_key: []const u8,
    secret_key: []const u8,
    timeout_ms: u32 = 60_000,

    /// Инициализирует клиент без сетевого запроса; строки config должны жить до deinit.
    pub fn init(io: std.Io, allocator: std.mem.Allocator, config: Settings) S3 {
        return .{
            .client = .{ .io = io, .allocator = allocator },
            .io = io,
            .allocator = allocator,
            .endpoint = config.endpoint,
            .region = config.region,
            .bucket = config.bucket,
            .access_key = config.access_key,
            .secret_key = config.secret_key,
        };
    }

    /// Закрывает соединения и освобождает клиент после остановки HTTP-обработчиков и workers.
    pub fn deinit(self: *S3) void {
        self.client.deinit();
        self.* = undefined;
    }

    /// Загружает или заменяет объект в бакете из настроек; использует таймаут putInBucket.
    pub fn put(
        self: *S3,
        arena: std.mem.Allocator,
        key: []const u8,
        mime: []const u8,
        data: []const u8,
    ) !void {
        return self.putInBucket(arena, self.bucket, key, mime, data);
    }

    /// Проверяет путь и загружает объект в указанный бакет с подписью SigV4.
    /// Общий таймаут, включая один повтор закрытого соединения, задаётся timeout_ms.
    pub fn putInBucket(
        self: *S3,
        arena: std.mem.Allocator,
        bucket: []const u8,
        key: []const u8,
        mime: []const u8,
        data: []const u8,
    ) !void {
        // Keys are generated by the backend; never use a client filename as a path.
        try validateBucket(bucket);
        try validateKey(key);

        const path = try std.fmt.allocPrint(arena, "/{s}/{s}", .{ bucket, key });
        const url = try std.fmt.allocPrint(arena, "{s}{s}", .{ self.endpoint, path });
        const scheme_end = std.mem.indexOf(u8, self.endpoint, "://") orelse return error.InvalidConfiguration;
        const host = self.endpoint[scheme_end + 3 ..];
        const timestamp = try formatTimestamp(self.io);
        const signed = try signPut(arena, self.access_key, self.secret_key, self.region, host, path, mime, data, &timestamp);

        // Ограничиваем всю сетевую операцию; повтор не продлевает исходный таймаут.
        const Result = union(enum) { request: anyerror!void, deadline: anyerror!void };
        var buffer: [2]Result = undefined;
        var select = std.Io.Select(Result).init(self.io, &buffer);
        defer select.cancelDiscard();

        try select.concurrent(.request, sendWithRetry, .{ self, url, host, mime, data, signed, &timestamp, .PUT });
        try select.concurrent(.deadline, deadline, .{ self.io, self.timeout_ms });

        switch (try select.await()) {
            .request => |result| try result,
            .deadline => return error.StorageTimeout,
        }
    }

    /// Удаляет объект из бакета в настройках; использует таймаут deleteInBucket.
    pub fn delete(self: *S3, arena: std.mem.Allocator, key: []const u8) !void {
        return self.deleteInBucket(arena, self.bucket, key);
    }

    /// Удаляет объект из указанного бакета подписанным DELETE; ожидает HTTP 204.
    /// Операция, включая один повтор закрытого соединения, ограничена timeout_ms.
    pub fn deleteInBucket(self: *S3, arena: std.mem.Allocator, bucket: []const u8, key: []const u8) !void {
        try validateBucket(bucket);
        try validateKey(key);

        const path = try std.fmt.allocPrint(arena, "/{s}/{s}", .{ bucket, key });
        const url = try std.fmt.allocPrint(arena, "{s}{s}", .{ self.endpoint, path });
        const delimiter = std.mem.indexOf(u8, self.endpoint, "://") orelse return error.InvalidConfiguration;
        const host = self.endpoint[delimiter + 3 ..];
        const timestamp = try formatTimestamp(self.io);
        const signed = try signRequest(arena, "DELETE", self.access_key, self.secret_key, self.region, host, path, "application/octet-stream", "", &timestamp);

        const Result = union(enum) { request: anyerror!void, deadline: anyerror!void };
        var buffer: [2]Result = undefined;
        var select = std.Io.Select(Result).init(self.io, &buffer);
        defer select.cancelDiscard();

        try select.concurrent(.request, sendWithRetry, .{ self, url, host, "application/octet-stream", "", signed, &timestamp, .DELETE });
        try select.concurrent(.deadline, deadline, .{ self.io, self.timeout_ms });

        switch (try select.await()) {
            .request => |result| try result,
            .deadline => return error.StorageTimeout,
        }
    }

    /// Читает объект из бакета в настройках в arena с ограничением размера max_bytes.
    pub fn get(self: *S3, arena: std.mem.Allocator, key: []const u8, max_bytes: usize) ![]const u8 {
        return self.getInBucket(arena, self.bucket, key, max_bytes);
    }

    /// Читает объект из указанного бакета; возвращаемые байты живут до освобождения arena.
    /// Буфер ограничен max_bytes, операция с повтором — timeout_ms; ожидает HTTP 200.
    pub fn getInBucket(
        self: *S3,
        arena: std.mem.Allocator,
        bucket: []const u8,
        key: []const u8,
        max_bytes: usize,
    ) ![]const u8 {
        try validateBucket(bucket);
        try validateKey(key);

        const path = try std.fmt.allocPrint(arena, "/{s}/{s}", .{ bucket, key });
        const url = try std.fmt.allocPrint(arena, "{s}{s}", .{ self.endpoint, path });
        const scheme_end = std.mem.indexOf(u8, self.endpoint, "://") orelse return error.InvalidConfiguration;
        const host = self.endpoint[scheme_end + 3 ..];
        const timestamp = try formatTimestamp(self.io);
        const signed = try signRequest(arena, "GET", self.access_key, self.secret_key, self.region, host, path, "application/octet-stream", "", &timestamp);

        var writer: std.Io.Writer = .fixed(try arena.alloc(u8, max_bytes));
        const Result = union(enum) { request: anyerror!void, deadline: anyerror!void };
        var buffer: [2]Result = undefined;
        var select = std.Io.Select(Result).init(self.io, &buffer);
        defer select.cancelDiscard();

        try select.concurrent(.request, getWithRetry, .{ self, url, host, signed, &timestamp, &writer });
        try select.concurrent(.deadline, deadline, .{ self.io, self.timeout_ms });

        switch (try select.await()) {
            .request => |result| try result,
            .deadline => return error.StorageTimeout,
        }

        return writer.buffered();
    }

    /// Выполняет GET и повторяет его один раз только при HttpConnectionClosing.
    fn getWithRetry(
        self: *S3,
        url: []const u8,
        host: []const u8,
        signed: Signed,
        timestamp: []const u8,
        writer: *std.Io.Writer,
    ) anyerror!void {
        self.getOnce(url, host, signed, timestamp, writer) catch |err| {
            if (err != error.HttpConnectionClosing) return err;
            // No response headers or body arrived; the failed connection was discarded.
            std.log.debug("S3 GetObject connection closed before response; retrying once", .{});
            try self.getOnce(url, host, signed, timestamp, writer);
        };
    }

    /// Выполняет один подписанный GET через общий HTTP-клиент без перехода по редиректам.
    fn getOnce(
        self: *S3,
        url: []const u8,
        host: []const u8,
        signed: Signed,
        timestamp: []const u8,
        writer: *std.Io.Writer,
    ) anyerror!void {
        const result = try self.client.fetch(.{
            .location = .{ .url = url },
            .method = .GET,
            .response_writer = writer,
            .redirect_behavior = .unhandled,
            .keep_alive = true,
            .headers = .{
                .host = .{ .override = host },
                .authorization = .{ .override = signed.authorization },
                .content_type = .{ .override = "application/octet-stream" },
            },
            .extra_headers = &.{
                .{ .name = "x-amz-content-sha256", .value = &signed.payload_hash },
                .{ .name = "x-amz-date", .value = timestamp },
            },
        });

        if (result.status != .ok) {
            std.log.warn("S3 GetObject returned HTTP {d}", .{@intFromEnum(result.status)});
            return error.StorageRejected;
        }
    }

    /// Выполняет PUT или DELETE, повторяя тот же запрос один раз при HttpConnectionClosing.
    fn sendWithRetry(
        self: *S3,
        url: []const u8,
        host: []const u8,
        mime: []const u8,
        data: []const u8,
        signed: Signed,
        timestamp: []const u8,
        method: std.http.Method,
    ) anyerror!void {
        self.sendOnce(url, host, mime, data, signed, timestamp, method) catch |err| {
            if (err != error.HttpConnectionClosing) return err;
            // PUT of the same bytes/key and DELETE are idempotent. Keep the original deadline.
            std.log.debug("S3 {s} connection closed before response; retrying once", .{@tagName(method)});
            try self.sendOnce(url, host, mime, data, signed, timestamp, method);
        };
    }

    /// Выполняет одну отправку, освобождает запрос и проверяет HTTP-статус без перехода по редиректам.
    /// Ошибочное соединение исключается из пула; HTTP 204 обрабатывается без ожидания тела.
    fn sendOnce(
        self: *S3,
        url: []const u8,
        host: []const u8,
        mime: []const u8,
        data: []const u8,
        signed: Signed,
        timestamp: []const u8,
        method: std.http.Method,
    ) anyerror!void {
        var request = try self.client.request(method, try std.Uri.parse(url), .{
            .redirect_behavior = .unhandled,
            .keep_alive = true,
            .headers = .{
                .host = .{ .override = host },
                .authorization = .{ .override = signed.authorization },
                .content_type = .{ .override = mime },
            },
            .extra_headers = &.{
                .{ .name = "x-amz-content-sha256", .value = &signed.payload_hash },
                .{ .name = "x-amz-date", .value = timestamp },
            },
        });
        defer request.deinit();

        // Do not drain a failed/canceled response while returning its connection to the pool.
        errdefer if (request.connection) |connection| {
            connection.closing = true;
        };

        if (method == .PUT) {
            request.transfer_encoding = .{ .content_length = data.len };
            var body = try request.sendBodyUnflushed(&.{});
            try body.writer.writeAll(data);
            try body.end();
            try request.connection.?.flush();
        } else {
            try request.sendBodiless();
        }

        var response = try request.receiveHead(&.{});
        const status = response.head.status;

        if (status == .no_content) {
            // Zig 0.16 fetch waits for EOF on MinIO's persistent 204 without Content-Length.
            // A 204 ends at the headers, regardless of its framing headers.
            response.head.transfer_encoding = .none;
            response.head.content_length = 0;
            request.response_transfer_encoding = .none;
            request.response_content_length = 0;
        }

        const reader = response.reader(&.{});
        _ = reader.discardRemaining() catch return response.bodyErr() orelse error.ReadFailed;

        const expected: std.http.Status = if (method == .PUT) .ok else .no_content;
        if (status != expected) {
            // Do not log storage responses or credentials.
            std.log.warn("S3 {s} returned HTTP {d}", .{ if (method == .PUT) "PutObject" else "DeleteObject", @intFromEnum(status) });
            return error.StorageRejected;
        }
    }
};

/// Проверяет допустимое имя бакета для файловых операций; иначе InvalidBucket.
fn validateBucket(bucket: []const u8) !void {
    if (bucket.len < 3 or bucket.len > 63) return error.InvalidBucket;
    for (bucket) |c| {
        if (!(std.ascii.isLower(c) or std.ascii.isDigit(c) or c == '-' or c == '.')) return error.InvalidBucket;
    }

    if (!std.ascii.isAlphanumeric(bucket[0]) or !std.ascii.isAlphanumeric(bucket[bucket.len - 1])) return error.InvalidBucket;
}

/// Проверяет ключ из безопасных ASCII-символов без пустых, '.' и '..' сегментов пути.
fn validateKey(key: []const u8) !void {
    if (key.len == 0 or key.len > 1024) return error.InvalidObjectKey;
    for (key) |c| {
        if (!(std.ascii.isAlphanumeric(c) or c == '-' or c == '/' or c == '.' or c == '_')) return error.InvalidObjectKey;
    }

    var parts = std.mem.splitScalar(u8, key, '/');
    while (parts.next()) |part| {
        if (part.len == 0 or std.mem.eql(u8, part, ".") or std.mem.eql(u8, part, "..")) return error.InvalidObjectKey;
    }
}

/// Ожидает timeout_ms; завершение этой ветки Select означает истечение таймаута операции.
fn deadline(io: std.Io, timeout_ms: u32) anyerror!void {
    try std.Io.sleep(io, .fromMilliseconds(timeout_ms), .awake);
}

/// Заголовок Authorization и хеш тела для подписанного запроса; заголовок хранится в arena.
const Signed = struct {
    authorization: []const u8,
    payload_hash: [64]u8,
};

/// Возвращает SHA-256 данных в виде 64 строчных шестнадцатеричных символов.
fn sha256Hex(data: []const u8) [64]u8 {
    var digest: [32]u8 = undefined;
    Sha256.hash(data, &digest, .{});
    return std.fmt.bytesToHex(digest, .lower);
}

/// Вычисляет HMAC-SHA256 для данных с переданным ключом.
fn hmac(key: []const u8, data: []const u8) [32]u8 {
    var digest: [32]u8 = undefined;
    Hmac.create(&digest, data, key);
    return digest;
}

/// Создаёт подпись SigV4 для PUT; память заголовка Authorization выделяется в arena.
fn signPut(
    arena: std.mem.Allocator,
    access_key: []const u8,
    secret_key: []const u8,
    region: []const u8,
    host: []const u8,
    path: []const u8,
    mime: []const u8,
    data: []const u8,
    timestamp: []const u8,
) !Signed {
    return signRequest(arena, "PUT", access_key, secret_key, region, host, path, mime, data, timestamp);
}

/// Создаёт SigV4 Authorization и хеш тела для заданного метода, пути и времени UTC.
/// timestamp должен иметь формат YYYYMMDDTHHMMSSZ; параметры запроса не поддерживаются.
fn signRequest(
    arena: std.mem.Allocator,
    method: []const u8,
    access_key: []const u8,
    secret_key: []const u8,
    region: []const u8,
    host: []const u8,
    path: []const u8,
    mime: []const u8,
    data: []const u8,
    timestamp: []const u8,
) !Signed {
    const payload_hash = sha256Hex(data);
    const signed_headers = "content-type;host;x-amz-content-sha256;x-amz-date";

    const canonical = try std.fmt.allocPrint(
        arena,
        "{s}\n{s}\n\ncontent-type:{s}\nhost:{s}\nx-amz-content-sha256:{s}\nx-amz-date:{s}\n\n{s}\n{s}",
        .{ method, path, mime, host, payload_hash, timestamp, signed_headers, payload_hash },
    );

    const canonical_hash = sha256Hex(canonical);
    const scope = try std.fmt.allocPrint(arena, "{s}/{s}/s3/aws4_request", .{ timestamp[0..8], region });
    const to_sign = try std.fmt.allocPrint(arena, "AWS4-HMAC-SHA256\n{s}\n{s}\n{s}", .{ timestamp, scope, canonical_hash });

    const secret = try std.fmt.allocPrint(arena, "AWS4{s}", .{secret_key});
    const date_key = hmac(secret, timestamp[0..8]);
    const region_key = hmac(&date_key, region);
    const service_key = hmac(&region_key, "s3");
    const signing_key = hmac(&service_key, "aws4_request");
    const signature = std.fmt.bytesToHex(hmac(&signing_key, to_sign), .lower);

    return .{
        .payload_hash = payload_hash,
        .authorization = try std.fmt.allocPrint(
            arena,
            "AWS4-HMAC-SHA256 Credential={s}/{s}, SignedHeaders={s}, Signature={s}",
            .{ access_key, scope, signed_headers, signature },
        ),
    };
}

/// Форматирует текущее реальное время в UTC для SigV4; отрицательное время — InvalidClock.
fn formatTimestamp(io: std.Io) ![16]u8 {
    const seconds = std.Io.Timestamp.now(io, .real).toSeconds();
    if (seconds < 0) return error.InvalidClock;

    return timestampFromSeconds(@intCast(seconds));
}

/// Преобразует секунды Unix в строку UTC YYYYMMDDTHHMMSSZ.
fn timestampFromSeconds(seconds: u64) ![16]u8 {
    const epoch: std.time.epoch.EpochSeconds = .{ .secs = seconds };
    const year_day = epoch.getEpochDay().calculateYearDay();
    const month_day = year_day.calculateMonthDay();
    const time = epoch.getDaySeconds();

    var result: [16]u8 = undefined;
    _ = try std.fmt.bufPrint(&result, "{d:0>4}{d:0>2}{d:0>2}T{d:0>2}{d:0>2}{d:0>2}Z", .{
        year_day.year,          month_day.month.numeric(), @as(u6, month_day.day_index) + 1,
        time.getHoursIntoDay(), time.getMinutesIntoHour(), time.getSecondsIntoMinute(),
    });

    return result;
}

test "S3 timestamp uses UTC including leap day" {
    try std.testing.expectEqualStrings("19700101T000000Z", &(try timestampFromSeconds(0)));
    try std.testing.expectEqualStrings("20240229T123456Z", &(try timestampFromSeconds(1709210096)));
}

