const std = @import("std");
const Config = @import("../config.zig").Config;
const Sha256 = std.crypto.hash.sha2.Sha256;
const Hmac = std.crypto.auth.hmac.sha2.HmacSha256;

pub const S3 = struct {
    io: std.Io,
    allocator: std.mem.Allocator,
    endpoint: []const u8,
    region: []const u8,
    bucket: []const u8,
    access_key: []const u8,
    secret_key: []const u8,
    timeout_ms: u32 = 60_000,

    pub fn init(io: std.Io, allocator: std.mem.Allocator, config: Config) S3 {
        return .{
            .io = io,
            .allocator = allocator,
            .endpoint = config.s3_endpoint,
            .region = config.s3_region,
            .bucket = config.s3_bucket,
            .access_key = config.s3_access_key,
            .secret_key = config.s3_secret_key,
        };
    }

    pub fn put(self: S3, arena: std.mem.Allocator, key: []const u8, mime: []const u8, data: []const u8) !void {
        // Keys are generated by the backend; never use a client filename as a path.
        for (key) |c| {
            if (!(std.ascii.isAlphanumeric(c) or c == '-' or c == '/')) return error.InvalidObjectKey;
        }
        const path = try std.fmt.allocPrint(arena, "/{s}/{s}", .{ self.bucket, key });
        const url = try std.fmt.allocPrint(arena, "{s}{s}", .{ self.endpoint, path });
        const scheme_end = std.mem.indexOf(u8, self.endpoint, "://") orelse return error.InvalidConfiguration;
        const host = self.endpoint[scheme_end + 3 ..];
        const timestamp = try formatTimestamp(self.io);
        const signed = try signPut(arena, self.access_key, self.secret_key, self.region, host, path, mime, data, &timestamp);

        // Bound S3 work so a stalled storage server does not retain a DB row lock indefinitely.
        const Result = union(enum) { request: anyerror!void, deadline: anyerror!void };
        var buffer: [2]Result = undefined;
        var select = std.Io.Select(Result).init(self.io, &buffer);
        defer select.cancelDiscard();
        try select.concurrent(.request, send, .{ self, url, host, mime, data, signed, &timestamp });
        try select.concurrent(.deadline, deadline, .{ self.io, self.timeout_ms });
        switch (try select.await()) {
            .request => |result| try result,
            .deadline => return error.StorageTimeout,
        }
    }

    fn send(self: S3, url: []const u8, host: []const u8, mime: []const u8, data: []const u8, signed: Signed, timestamp: []const u8) anyerror!void {
        // A client per operation avoids sharing request state between HTTP workers.
        var client: std.http.Client = .{ .io = self.io, .allocator = self.allocator };
        defer client.deinit();
        const result = try client.fetch(.{
            .location = .{ .url = url },
            .method = .PUT,
            .payload = data,
            .redirect_behavior = .unhandled,
            .keep_alive = false,
            .headers = .{
                .host = .{ .override = host },
                .authorization = .{ .override = signed.authorization },
                .content_type = .{ .override = mime },
            },
            .extra_headers = &.{
                .{ .name = "x-amz-content-sha256", .value = &signed.payload_hash },
                .{ .name = "x-amz-date", .value = timestamp },
            },
        });
        if (result.status != .ok) {
            // Do not log storage responses or credentials.
            std.log.warn("S3 PutObject returned HTTP {d}", .{@intFromEnum(result.status)});
            return error.StorageRejected;
        }
    }
};

fn deadline(io: std.Io, timeout_ms: u32) anyerror!void {
    try std.Io.sleep(io, .fromMilliseconds(timeout_ms), .awake);
}

const Signed = struct {
    authorization: []const u8,
    payload_hash: [64]u8,
};

fn hashHex(data: []const u8) [64]u8 {
    var digest: [32]u8 = undefined;
    Sha256.hash(data, &digest, .{});
    return std.fmt.bytesToHex(digest, .lower);
}

fn hmac(key: []const u8, data: []const u8) [32]u8 {
    var digest: [32]u8 = undefined;
    Hmac.create(&digest, data, key);
    return digest;
}

fn signPut(arena: std.mem.Allocator, access_key: []const u8, secret_key: []const u8, region: []const u8, host: []const u8, path: []const u8, mime: []const u8, data: []const u8, timestamp: []const u8) !Signed {
    const payload_hash = hashHex(data);
    const signed_headers = "content-type;host;x-amz-content-sha256;x-amz-date";
    const canonical = try std.fmt.allocPrint(
        arena,
        "PUT\n{s}\n\ncontent-type:{s}\nhost:{s}\nx-amz-content-sha256:{s}\nx-amz-date:{s}\n\n{s}\n{s}",
        .{ path, mime, host, payload_hash, timestamp, signed_headers, payload_hash },
    );
    const canonical_hash = hashHex(canonical);
    const scope = try std.fmt.allocPrint(arena, "{s}/{s}/s3/aws4_request", .{ timestamp[0..8], region });
    const to_sign = try std.fmt.allocPrint(arena, "AWS4-HMAC-SHA256\n{s}\n{s}\n{s}", .{ timestamp, scope, canonical_hash });
    const secret = try std.fmt.allocPrint(arena, "AWS4{s}", .{secret_key});
    const date_key = hmac(secret, timestamp[0..8]);
    const region_key = hmac(&date_key, region);
    const service_key = hmac(&region_key, "s3");
    const signing_key = hmac(&service_key, "aws4_request");
    const signature = std.fmt.bytesToHex(hmac(&signing_key, to_sign), .lower);
    return .{
        .payload_hash = payload_hash,
        .authorization = try std.fmt.allocPrint(
            arena,
            "AWS4-HMAC-SHA256 Credential={s}/{s}, SignedHeaders={s}, Signature={s}",
            .{ access_key, scope, signed_headers, signature },
        ),
    };
}

fn formatTimestamp(io: std.Io) ![16]u8 {
    const seconds = std.Io.Timestamp.now(io, .real).toSeconds();
    if (seconds < 0) return error.InvalidClock;
    return timestampFromSeconds(@intCast(seconds));
}

fn timestampFromSeconds(seconds: u64) ![16]u8 {
    const epoch: std.time.epoch.EpochSeconds = .{ .secs = seconds };
    const year_day = epoch.getEpochDay().calculateYearDay();
    const month_day = year_day.calculateMonthDay();
    const time = epoch.getDaySeconds();
    var result: [16]u8 = undefined;
    _ = try std.fmt.bufPrint(&result, "{d:0>4}{d:0>2}{d:0>2}T{d:0>2}{d:0>2}{d:0>2}Z", .{
        year_day.year,          month_day.month.numeric(), @as(u6, month_day.day_index) + 1,
        time.getHoursIntoDay(), time.getMinutesIntoHour(), time.getSecondsIntoMinute(),
    });
    return result;
}

test "S3 timestamp uses UTC including leap day" {
    try std.testing.expectEqualStrings("19700101T000000Z", &(try timestampFromSeconds(0)));
    try std.testing.expectEqualStrings("20240229T123456Z", &(try timestampFromSeconds(1709210096)));
}

test "SigV4 PUT matches an independently calculated Python hashlib fixture" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const signed = try signPut(arena.allocator(), "test-access", "test-secret", "us-east-1", "127.0.0.1:9000", "/uploads/tracks/11111111-1111-4111-8111-111111111111", "audio/mpeg", "hello musica", "20261006T010203Z");
    try std.testing.expectEqualStrings(
        "AWS4-HMAC-SHA256 Credential=test-access/20261006/us-east-1/s3/aws4_request, SignedHeaders=content-type;host;x-amz-content-sha256;x-amz-date, Signature=407fe20689a388a1dfb0e41c01a4fcb96f728a20e409a2455ff998fb8a336edf",
        signed.authorization,
    );
}

fn mockStorage(io: std.Io, server: *std.Io.net.Server, status: []const u8) !void {
    const stream = try server.accept(io);
    defer stream.close(io);
    var read_buffer: [4096]u8 = undefined;
    var reader = stream.reader(io, &read_buffer);
    const request_line = (try reader.interface.takeDelimiter('\n')) orelse return error.EndOfStream;
    try std.testing.expectEqualStrings("PUT /uploads/tracks/test HTTP/1.1\r", request_line);
    var has_auth = false;
    var has_mime = false;
    var has_length = false;
    var has_hash = false;
    while (true) {
        const line = (try reader.interface.takeDelimiter('\n')) orelse return error.EndOfStream;
        if (std.mem.eql(u8, line, "\r")) break;
        if (std.mem.startsWith(u8, line, "authorization: AWS4-HMAC-SHA256 ")) has_auth = true;
        if (std.mem.eql(u8, line, "content-type: audio/mpeg\r")) has_mime = true;
        if (std.mem.eql(u8, line, "content-length: 4\r")) has_length = true;
        if (std.mem.startsWith(u8, line, "x-amz-content-sha256: ")) has_hash = true;
    }
    try std.testing.expect(has_auth and has_mime and has_length and has_hash);
    var payload: [4]u8 = undefined;
    try reader.interface.readSliceAll(&payload);
    try std.testing.expectEqualSlices(u8, &.{ 0, 255, 1, 2 }, &payload);
    var write_buffer: [256]u8 = undefined;
    var writer = stream.writer(io, &write_buffer);
    try writer.interface.print("HTTP/1.1 {s}\r\nContent-Length: 0\r\nConnection: close\r\n\r\n", .{status});
    try writer.interface.flush();
}

test "S3 sends a signed binary PUT and propagates storage rejection" {
    const io = std.testing.io;
    for ([_][]const u8{ "200 OK", "403 Forbidden", "307 Temporary Redirect" }) |status| {
        const address: std.Io.net.IpAddress = .{ .ip4 = .{ .bytes = .{ 127, 0, 0, 1 }, .port = 0 } };
        var server = try address.listen(io, .{});
        defer server.deinit(io);
        var future = try io.concurrent(mockStorage, .{ io, &server, status });
        defer future.cancel(io) catch {};
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        const endpoint = try std.fmt.allocPrint(arena.allocator(), "http://127.0.0.1:{d}", .{server.socket.address.ip4.port});
        const storage: S3 = .{
            .io = io,
            .allocator = std.testing.allocator,
            .endpoint = endpoint,
            .region = "us-east-1",
            .bucket = "uploads",
            .access_key = "testaccess",
            .secret_key = "test-secret",
        };
        if (std.mem.startsWith(u8, status, "200")) {
            try storage.put(arena.allocator(), "tracks/test", "audio/mpeg", &.{ 0, 255, 1, 2 });
        } else {
            try std.testing.expectError(error.StorageRejected, storage.put(arena.allocator(), "tracks/test", "audio/mpeg", &.{ 0, 255, 1, 2 }));
        }
        try future.await(io);
    }
}

fn stalledStorage(io: std.Io, server: *std.Io.net.Server) !void {
    const stream = try server.accept(io);
    defer stream.close(io);
    try std.Io.sleep(io, .fromSeconds(10), .awake);
}

test "stalled S3 request is canceled at its deadline" {
    const io = std.testing.io;
    const address: std.Io.net.IpAddress = .{ .ip4 = .{ .bytes = .{ 127, 0, 0, 1 }, .port = 0 } };
    var server = try address.listen(io, .{});
    defer server.deinit(io);
    var future = try io.concurrent(stalledStorage, .{ io, &server });
    defer future.cancel(io) catch {};
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const endpoint = try std.fmt.allocPrint(arena.allocator(), "http://127.0.0.1:{d}", .{server.socket.address.ip4.port});
    const storage: S3 = .{
        .io = io,
        .allocator = std.testing.allocator,
        .endpoint = endpoint,
        .region = "us-east-1",
        .bucket = "uploads",
        .access_key = "testaccess",
        .secret_key = "test-secret",
        .timeout_ms = 50,
    };
    try std.testing.expectError(error.StorageTimeout, storage.put(arena.allocator(), "tracks/test", "audio/mpeg", "test"));
}
